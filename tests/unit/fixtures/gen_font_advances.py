#!/usr/bin/env python3
"""Writes font_advances.lua: the advance width in px of every character a chip caption can use, in the font chain
Factorio renders button captions with (default-semibold, 14 px at UI scale 1.0), for every locale the mod ships.
chip_width_test.lua measures the filter chip captions with it.

Advances come from FreeType with its default hinting at 14 px, as the engine rasterises: unhinted advances rounded
per glyph differ for some letters ("x" is 7 px hinted, 6 rounded), and the hinted ones match the game to the pixel.

usage: python -m venv /tmp/ftvenv && /tmp/ftvenv/bin/pip install freetype-py
       /tmp/ftvenv/bin/python gen_font_advances.py [factorio-data-dir] [mod-root]
Rerun after a Factorio update or when a translation brings characters the table lacks (the test names them).
"""
import json
import os
import sys
import freetype

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/factorio/data")
MOD = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "..", "..", "..", "cybersyn")
FONT = "default-semibold"
SIZE = 14

# Whole blocks so a new translation in these scripts needs no regeneration; anything else comes from the cfg files.
BLOCKS = [(0x20, 0x7E), (0xA0, 0x17F), (0x400, 0x4FF), (0x2000, 0x206F)]


def core_chain(locale):
    for name in (locale, "en"):
        path = os.path.join(DATA, "core", "locale", name, "info.json")
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                fonts = json.load(f).get("font")
            if fonts and FONT in fonts:
                return name, [p.replace("__core__", os.path.join(DATA, "core")) for p in fonts[FONT]]
    raise SystemExit("no %s font chain for %s" % (FONT, locale))


def locale_chars(path):
    chars = set()
    for root, _, files in os.walk(path):
        for name in files:
            if name.endswith(".cfg"):
                with open(os.path.join(root, name), encoding="utf-8") as f:
                    chars.update(ord(c) for c in f.read() if c >= " ")
    return chars


def main():
    locales = sorted(d for d in os.listdir(os.path.join(MOD, "locale")) if os.path.isdir(os.path.join(MOD, "locale", d)))
    cps = locale_chars(os.path.join(MOD, "locale"))
    for lo, hi in BLOCKS:
        cps.update(range(lo, hi + 1))
    fonts = {}

    def font(path):
        if path not in fonts:
            face = freetype.Face(path)
            face.set_pixel_sizes(0, SIZE)
            fonts[path] = face
        return fonts[path]

    chains, chain_of = {}, {}
    for loc in locales:
        source, paths = core_chain(loc)
        chain_of[loc] = source
        if source in chains:
            continue
        adv = {}
        for cp in sorted(cps):
            for p in paths:
                face = font(p)
                if face.get_char_index(cp):
                    face.load_char(cp, freetype.FT_LOAD_DEFAULT)
                    adv[cp] = face.glyph.advance.x // 64
                    break
        chains[source] = ([os.path.basename(p) for p in paths], adv)

    out = ["-- Generated by gen_font_advances.py from Factorio's %s fonts; do not edit." % FONT,
           "-- chains[name].advance[codepoint] = advance width in px at %d px (UI scale 1.0), from the first font of the" % SIZE,
           "-- chain that has the glyph, as Factorio falls back. locales maps each mod locale to the core locale whose",
           "-- chain it renders with (its own when Factorio ships one with a font list, else en's).",
           "return {", "\tsize = %d," % SIZE, "\tlocales = {"]
    for loc in locales:
        out.append('\t\t["%s"] = "%s",' % (loc, chain_of[loc]))
    out.append("\t},")
    out.append("\tchains = {")
    for name, (files, adv) in sorted(chains.items()):
        out.append('\t\t["%s"] = {' % name)
        out.append("\t\t\tfonts = { %s }," % ", ".join('"%s"' % f for f in files))
        out.append("\t\t\tadvance = {")
        row = []
        for cp, a in sorted(adv.items()):
            row.append("[%d]=%d" % (cp, a))
            if len(row) == 14:
                out.append("\t\t\t\t" + ", ".join(row) + ",")
                row = []
        if row:
            out.append("\t\t\t\t" + ", ".join(row) + ",")
        out.append("\t\t\t},")
        out.append("\t\t},")
    out.append("\t},")
    out.append("}")
    with open(os.path.join(HERE, "font_advances.lua"), "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")


main()
